#!/usr/bin/env python3
"""Generate LVGL 9 RGB565A8 resources from approved Trae robot PNGs."""

import argparse
import pathlib
import sys
from typing import Dict

from PIL import Image


ROOT = pathlib.Path(__file__).resolve().parents[1]
ASSET_ROOT = ROOT / "main" / "apps" / "app_codex_status" / "assets"
SOURCE_ROOT = ASSET_ROOT / "source"
HEADER_PATH = ASSET_ROOT / "trae_robot_assets.h"
SOURCE_PATH = ASSET_ROOT / "trae_robot_assets.cpp"

MANIFEST = (
    ("trae_robot_head", SOURCE_ROOT / "trae_robot_head.png"),
    ("trae_robot_idle", SOURCE_ROOT / "trae_robot_idle.png"),
    ("trae_robot_action", SOURCE_ROOT / "trae_robot_action.png"),
)


def rgb565a8_bytes(path: pathlib.Path) -> tuple[int, int, bytes]:
    image = Image.open(path).convert("RGBA")
    color = bytearray()
    alpha = bytearray()
    for red, green, blue, opacity in image.getdata():
        value = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
        color.extend((value & 0xFF, value >> 8))
        alpha.append(opacity)
    return image.width, image.height, bytes(color + alpha)


def render_byte_rows(data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), 24):
        values = ", ".join(f"0x{value:02X}" for value in data[offset : offset + 24])
        rows.append(f"    {values},")
    return "\n".join(rows)


def render_header() -> str:
    declarations = "\n".join(
        f"extern const lv_image_dsc_t {name};" for name, _ in MANIFEST
    )
    return f"""// Generated by scripts/generate_trae_robot_assets.py. Do not edit.
#pragma once

#include <lvgl.h>

#ifdef __cplusplus
extern "C" {{
#endif

{declarations}

#ifdef __cplusplus
}}
#endif
"""


def render_source() -> str:
    resources = []
    for name, path in MANIFEST:
        width, height, data = rgb565a8_bytes(path)
        resources.append(
            f"""alignas(4) static const uint8_t {name}_map[] = {{
{render_byte_rows(data)}
}};

const lv_image_dsc_t {name} = {{
    {{ LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565A8, 0, {width}, {height}, {width * 2}, 0 }},
    sizeof({name}_map),
    {name}_map,
    nullptr,
}};"""
        )
    return (
        "// Generated by scripts/generate_trae_robot_assets.py. Do not edit.\n"
        '#include "trae_robot_assets.h"\n\n'
        + "\n\n".join(resources)
        + "\n"
    )


def render_outputs() -> Dict[pathlib.Path, str]:
    return {
        HEADER_PATH: render_header(),
        SOURCE_PATH: render_source(),
    }


def check_outputs(outputs: Dict[pathlib.Path, str]) -> int:
    stale = []
    for path, expected in outputs.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            stale.append(path)
    if stale:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the tracked generated outputs differ",
    )
    args = parser.parse_args()
    outputs = render_outputs()

    if args.check:
        return check_outputs(outputs)

    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
